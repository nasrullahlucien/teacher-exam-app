def organize_major():
    major_path = os.path.join(QUESTIONS_DIR, "kb-major.json")
    with open(major_path, "r", encoding="utf-8") as f:
        all_qs = json.load(f)

    print(f"Loaded {len(all_qs)} questions from kb-major.json")
    manifest_files = []

    for group in MAJOR_SYLLABUS:
        disc_folder = os.path.join(QUESTIONS_DIR, "kb-major", group["folder"])
        os.makedirs(disc_folder, exist_ok=True)
        disc_name = group["discipline"]

        for filename, topic_name in group["topics"]:
            matched_qs = [
                q for q in all_qs
                if q.get("discipline") == disc_name and q.get("topic") == topic_name
            ]
            file_rel = f"kb-major/{group['folder']}/{filename}"
            file_abs = os.path.join(disc_folder, filename)

            with open(file_abs, "w", encoding="utf-8") as f:
                json.dump(matched_qs, f, ensure_ascii=False, indent=2)

            manifest_files.append(file_rel)
            print(f"  [kb-major] Saved {len(matched_qs)} questions to {file_rel}")

    return manifest_files

