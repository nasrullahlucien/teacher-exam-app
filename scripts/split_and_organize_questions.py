def organize_other_subjects():
    manifest = {}
    for sub_id, topic_list in OTHER_SUBJECTS.items():
        src_path = os.path.join(QUESTIONS_DIR, f"{sub_id}.json")
        with open(src_path, "r", encoding="utf-8") as f:
            qs = json.load(f)

        sub_folder = os.path.join(QUESTIONS_DIR, sub_id)
        os.makedirs(sub_folder, exist_ok=True)
        manifest[sub_id] = []

        for filename, topic_filters in topic_list:
            matched_qs = [q for q in qs if q.get("topic") in topic_filters]
            file_rel = f"{sub_id}/{filename}"
            file_abs = os.path.join(sub_folder, filename)

            with open(file_abs, "w", encoding="utf-8") as f:
                json.dump(matched_qs, f, ensure_ascii=False, indent=2)

            manifest[sub_id].append(file_rel)
            print(f"  [{sub_id}] Saved {len(matched_qs)} questions to {file_rel}")

    return manifest

